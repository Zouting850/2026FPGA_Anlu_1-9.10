// ============================================================
// bg_store.v
// M2 背景帧存储 —— 片内 ERAM32K 池 + ERAM9K 池 混合
//
// ------------------------------------------------------------
// 为什么必须混合（历史：曾经是"单一 9K 推断阵列"，已被真实构建证伪）
// ------------------------------------------------------------
// 背景帧 = 376x240x8bit = 90,240 B = 705 kbit。
// EG4S20BG256 的片内 ERAM 有两级，是**两个独立资源池、两个独立配额**：
//
//   池             容量公式                        可用字节   TD 的配额名
//   ------------- --------------------------------- ---------- -------------
//   ERAM9K   x64  64 x 9 kbit  = 576 kbit = 72 KB   65,536 B   #bram9k / out of 64
//   ERAM32K  x16  16 x 32 kbit = 512 kbit = 64 KB   65,536 B   #bram32k / out of 16
//   ------------- --------------------------------- ---------- -------------
//   合计          1088 kbit = 136 KB                131,072 B
//
//   （1088 kbit 与 arch/device_resource.csv 的 ERAMs(Kbits)=1088 完全对上。）
//
// 关键坑：**9K 池单池装不下整帧**。
//   9K 池理论最优打包 = 每块 1024 B（1Kx9 模式：1024 深 x 9 位，8 位宽只用 8 位）
//   → 64 x 1024 B = 65,536 B，而整帧要 90,240 B。**结构性不足，与打包技巧无关。**
//   实测更糟：TD 把深度 90240 向上对齐到 2^17 = 131072，于是用了 128 块
//   （>2 倍浪费），布线阶段直接
//       PHY-9013 ERROR: Design's emb number = 128, exceeds the limit 64.
//
//   而这个"128 块全部来自 bg_store"是门级面积报告确认过的——设计里其他模块
//   bram 列全是 0（投影直方图走寄存器阵列）。所以本模块是唯一的阻断源。
//
// ------------------------------------------------------------
// 划分方案（用户拍定：片上 32K + 9K 混合，不引入 SDRAM）
// ------------------------------------------------------------
//   像素 [0 .. 65535]        -> ERAM32K 池，16 块原语，块内 2K x 16 字
//   像素 [65536 .. 90239]    -> ERAM9K 池，1 个 32768 深 x 8 位推断阵列
//
//   为什么这么切：
//   1) ERAM32K 单块 = 2K x 16 = 32 kbit = **4096 B**（数据手册 DS301：
//      "内置 16 块 32Kb RAM，可独立配置为 2Kx16 或者 4Kx8"）。
//      16 块 x 2048 字 = 32,768 字，每字塞 2 个像素 -> 恰好 65,536 像素。
//      即 **16 块原语刚好一口气吃掉 64 KB**，一点不剩——所以上界就取 65536。
//   2) 剩余 90,240 - 65,536 = 24,704 B。阵列深度取 **32768（2^15）**而不是
//      24704——因为 TD 按 2 的幂对齐深度，24704 也会被抬到 32768，
//      写成 2^15 反而让 TD 打包可预测（实测 32 块，池内余 32 块）。
//      多出来的 8064 B 是"对齐税"，换来的是 9K 池只用一半，留足后续余量。
//
//   ⚠️ ERAM32K 在物理上分布在 **IO 空隙**里（不是和 ERAM9K 一起排在 PFB 阵列中），
//      所以有位置约束，TD 报错码 USR-8043「非法的 BRAM32K 位置」。
//      本模块用满 16 块 = 该池全部，不与其他模块争抢。
//
// ------------------------------------------------------------
// 字内字节组织 + 同拍读写不冲突的证明
// ------------------------------------------------------------
//   字 W 的字节布局：低字节 = 像素 2W，高字节 = 像素 2W+1。
//   读走端口 B，写在端口 A，两者地址在**同一拍内必然不同**（读 idx、写 idx-1）：
//
//     像素 N 为奇数（N=2W+1）：读 字W 高字节；写 像素N-1=2W -> 字W 低字节
//                              -> 同字不同字节，互不影响 ✔
//     像素 N 为偶数（N=2W）  ：读 字W 低字节；写 像素N-1=2W-1 -> 字W-1 高字节
//                              -> 不同字 ✔
//
//   所以**不依赖** BRAM 的 write-first / read-first 语义：
//   即便"同字同拍"那一拍也落在不同字节上，被读的那个字节永远不会被同拍改写。
//   写入用字节使能（bytewea=1 + bytea 选字节），dia 两个字节都送 wr_data，
//   由 bytea 决定实际写哪个——这样无论选哪半都是正确数据。
//
// 读延迟：端口 B 取 NOREG（不加输出寄存器），配 9K 推断阵列同样是 1 拍，
//         两路延迟一致，对外部（m2_engine）仍是"1 拍读延迟"，接口不变。
//
// 存储阵列**不加复位**，否则 TD 无法推断 ERAM9K/ERAM32K。上电内容未定义，
// 由 m2_engine 的"背景装载阶段"负责在前若干帧把 bg 灌成当前画面。
// ============================================================
`include "vision_def.v"

module bg_store
(
	input                       clk,
	// 读口
	input                       rd_en,
	input[16:0]                 rd_addr,      // 17 bit：90240 < 2^17
	output reg[7:0]             rd_data,
	// 写口
	input                       wr_en,
	input[16:0]                 wr_addr,
	input[7:0]                  wr_data
);

localparam DEPTH      = `CAM_FRAME_PIX;   // 90240

// ---- 划分常量（改动这里就等于改动"哪个池装多少"）----
localparam N32        = 16;               // ERAM32K 原语块数（该池全部）
localparam P32_PIX    = 65536;            // 2^16：32K 池覆盖的像素数 = 16 块 x 2048 字 x 2 像素
localparam P9_DEPTH   = 32768;            // 2^15：9K 池阵列深度（够装 24704，按 2 的幂对齐）

// ============================================================
// 地址拆分
//   P32_PIX = 2^16，所以"落在哪个池"就看 bit16：
//     bit16 == 0 -> 32K 池（像素 0 .. 65535）
//     bit16 == 1 -> 9K  池（像素 65536 .. 90239，减掉 65536 后就是 bit[15:0]）
// ============================================================
wire       rd_lo = ~rd_addr[16];
wire[14:0] rd_wad = rd_addr[15:1];        // 32K 池字地址 = 像素/2（15 bit，共 32768 字）
wire       rd_by  = rd_addr[0];           // 字内字节选择：0=低字节(偶像素) 1=高字节(奇像素)
wire[14:0] rd_i9  = rd_addr[14:0];        // 9K 池像素下标（减 65536 后 <= 24703 < 2^15）

wire       wr_lo = ~wr_addr[16];
wire[14:0] wr_wad = wr_addr[15:1];
wire       wr_by  = wr_addr[0];
wire[14:0] wr_i9  = wr_addr[14:0];

// 写使能（按池门控）
wire wr32 = wr_en &  wr_lo;
wire rd32 = rd_en &  rd_lo;
wire wr9  = wr_en & ~wr_lo;
wire rd9  = rd_en & ~rd_lo;

// ============================================================
// 9K 池：32768 深 x 8 位推断阵列（简单双口，1 拍读延迟）
// ============================================================
reg[7:0] mem9[0:P9_DEPTH-1];              // 不加复位，否则推断不出 ERAM

reg[7:0] d9;

always@(posedge clk)
begin
	if(wr9 == 1'b1)
		mem9[wr_i9] <= wr_data;
end

always@(posedge clk)
begin
	if(rd9 == 1'b1)
		d9 <= mem9[rd_i9];
end

// ============================================================
// 32K 池：调用 16 个 EG_PHY_BRAM32K 原语
//   每个 = 2K(2048) 字 x 16 位；端口 A 写、端口 B 读
//   字地址 [10:0] 选块内字，[14:11] 选块
// ============================================================
wire[15:0] dob_bus[0:N32-1];

genvar gi;

generate
	for(gi=0; gi<N32; gi=gi+1)
	begin : g_bram32
		// 块译码：16 块的块内地址线是同一组 [10:0]，靠**片选**区分落在哪一块。
		// 若不把块号并进 csa/csb，16 个实例的输入就完全一样，TD 会把它们
		// 合并成 1 块（实测 #bram32k 报 1 out of 16，静默丢 15 块容量！）。
		// gi 是 genvar 常量，所以这里的比较对每个实例都折叠成常数。
		wire csa_b = wr32 & (wr_wad[14:11] == gi);
		wire csb_b = rd32 & (rd_wad[14:11] == gi);

		EG_PHY_BRAM32K #(
			.MODE         ( "DP16K"   ),   // 双口；数据手册：32Kb 块可配 2Kx16
			.DATA_WIDTH_A ( "16"      ),
			.DATA_WIDTH_B ( "16"      ),
			.REGMODE_A    ( "NOREG"   ),   // 不加输出寄存器 -> 1 拍读延迟
			.REGMODE_B    ( "NOREG"   ),
			.WRITEMODE_A  ( "NORMAL"  ),
			.WRITEMODE_B  ( "NORMAL"  ),
			.SRMODE       ( "SYNC"    ),
			.READBACK     ( "OFF"     )
		) u_b32 (
			// ---- 端口 A：写 ----
			.doa      (               ),   // 不读，悬空
			.dia      ({wr_data,wr_data}), // 两个字节都送，由 bytea 选实际写入的那半
			.addra    (wr_wad[10:0]   ),
			.bytea    (wr_by          ),   // 0=写低字节(偶像素) 1=写高字节(奇像素)
			.bytewea  (1'b1           ),   // 使能字节写
			.csa      (csa_b          ),
			.wea      (csa_b          ),
			.clka     (clk            ),
			.rsta     (1'b0           ),   // 不复位
			.ocea     (1'b1           ),   // REGMODE_A=NOREG 时无意义
			// ---- 端口 B：读 ----
			.dob      (dob_bus[gi]    ),
			.dib      (16'd0          ),
			.addrb    (rd_wad[10:0]   ),
			.byteb    (1'b0           ),   // 读整字（16 位），字节选择在输出侧做
			.byteweb  (1'b0           ),
			.csb      (csb_b          ),
			.web      (1'b0           ),
			.clkb     (clk            ),
			.rstb     (1'b0           ),
			.oceb     (1'b1           )
		);
	end
endgenerate

// 块内 16 位输出按块号 16 选 1
//   dob 是端口 B 的 1 拍寄存输出，所以块号选择也必须用**打一拍的**块号
reg[3:0] rd_blk_d;

always@(posedge clk)
begin
	rd_blk_d <= rd_wad[14:11];
end

wire[15:0] dob_sel = dob_bus[rd_blk_d];   // 变量下标 -> 综合成 16:1 多路选择

// ============================================================
// 读数据回选：与 9K 阵列的 1 拍读延迟对齐
//   控制信号（池选择 / 字节选择）各打一拍，正好和 BRAM 输出同拍
// ============================================================
reg rd_lo_d;
reg rd_by_d;

always@(posedge clk)
begin
	rd_lo_d <= rd_lo;
	rd_by_d <= rd_by;
end

wire[7:0] d32 = rd_by_d ? dob_sel[15:8] : dob_sel[7:0];

always@(posedge clk)
begin
	if(rd_en == 1'b1)
		rd_data <= rd_lo_d ? d32 : d9;
end

endmodule
