// ============================================================
// morph.v
// M3 形态学：3x3 开运算（先腐蚀后膨胀），纯流式、无帧缓存
//
// 为什么要开运算：
//   帧差二值化出来的前景图里，最烦人的是"细碎的孤立噪点"——传感器噪声、
//   投影画面边缘抖动、曝光跳变都会撒下 1~2 像素的点。这些点在列投影上
//   会把一整列的计数抬高一点，多撒几列就会凭空多出一段。开运算（先腐蚀
//   把细结构吃掉，再膨胀把剩下的主体恢复原状）正好治这个：孤立点先被
//   腐蚀掉，后面的膨胀也不会让它复活（开运算非扩展），而人形宽数十像素，
//   腐蚀只会把轮廓削 1 圈，膨胀再补回来，形状基本不动。
//
// 文件里两个模块：
//   morph3x3  单个 3x3 级（参数 IS_ERODE 选腐蚀还是膨胀），流式
//   morph     开运算 = 腐蚀级 -> 膨胀级，并负责边界有效位
//
// 接口沿用 m2_engine 的前景流：v/fg/坐标 四路同拍。
// ============================================================
`include "vision_def.v"

// ------------------------------------------------------------
// morph3x3 —— 单个 3x3 级
//
// 【行缓冲为什么可以就是一个移位寄存器】
//   把一行像素按列序推进宽度 W 的移位寄存器，第 k 个像素在 k 拍后
//   到达左端被移出——所以"左端移出的 bit" = W 拍前写入的那一个像素。
//   本模块只在 v=1 时移位，而一行恰好 W 个有效像素（W = 376），所以
//   W 拍前 = 上一行的同一列。于是：
//       lb0[0] = 上一行 (row y-1) 第 x 列
//       lb1[0] = 上上行 (row y-2) 第 x 列
//   lb1 的输入取 lb0[0]，级联成两行延迟。**代价是行必须严格等宽**
//   （m2_engine 已保证每行恰 376 拍、多余 HREF 一律丢弃），否则
//   行与行会一行一行地漂。这也是这里不做"遇行首清零"的原因：
//   清零会把上一行的数据清掉，正好破坏要用的延迟。
//
// 【抽头与窗口中心】
//   每行各留 3 bit 列抽头（t0 当前行 / t1 = y-1 行 / t2 = y-2 行）。
//   时钟沿之后：
//       t0 = {x, x-1, x-2}     （t0[2] 最新）
//   所以**寄存器里**的 9 个抽头构成的 3x3 窗口，中心是 (列 x-2, 行 y-1)
//   ——注意是 x-2 不是 x-1：抽头是打拍后的值，比当前输入慢一拍。
//   本模块再把结果打一拍输出，于是
//       xo = x - 2, yo = y - 1
//   与输出的 mo 同拍对齐（相对**下一拍**的输入而言）。
//
// 【边界】
//   窗口完整要求 x >= 3（要 x-3 >= 0）、y >= 2（要 y-2 >= 0），
//   否则抽头里含的是上一行残留位或未初始化位。本模块不在这里设有效位，
//   只把 v 原样传下去——**保持流"全宽"**。原因见 morph 的注释：
//   一旦在这一级把边界拍成无效，下一级的行移位次数就不再是每行 W 次，
//   行对齐会一行一行漂掉。所以边界屏蔽统一放到两级之后的 morph 出口。
// ------------------------------------------------------------
module morph3x3
#(
	parameter IS_ERODE = 1        // 1 = 腐蚀（9 位与）；0 = 膨胀（9 位或）
)
(
	input                       clk,
	input                       rst_n,        // 低有效
	// ---- 输入像素流 ----
	input                       v,            // 有效（全宽流水位，不是"边界有效"）
	input                       b,            // 1 bit 前景位
	input[15:0]                 x,
	input[15:0]                 y,
	// ---- 3x3 结果（打一拍）----
	output reg                  vo,
	output reg                  mo,
	output reg[15:0]            xo,
	output reg[15:0]            yo
);

localparam W = `CAM_IMG_W;

// 两条行缓冲（每行延迟 1 行）+ 三组 3 bit 列抽头
reg[W-1:0] lb0;
reg[W-1:0] lb1;
reg[2:0]   t0;
reg[2:0]   t1;
reg[2:0]   t2;

// 行缓冲左端输出（这一拍的值 = 上一行同列 / 上上行同列）
wire p1 = lb0[0];
wire p2 = lb1[0];

// 9 个抽头（用这一拍寄存器的值 → 窗口中心列 x-2）
wire[8:0] win = {t2, t1, t0};

wire m_bit = IS_ERODE ? (&win) : (|win);

// 输出坐标：中心列 x-2、中心行 y-1；减法在边界处钳到 0，
// 避免 16 bit 无符号回绕出一串没意义的坐标（反正这些拍会被出口屏蔽）。
wire[15:0] xo_n = (x < 16'd2) ? 16'd0 : (x - 16'd2);
wire[15:0] yo_n = (y < 16'd1) ? 16'd0 : (y - 16'd1);

always@(posedge clk or negedge rst_n)
begin
	if(!rst_n)
	begin
		lb0 <= {W{1'b0}};
		lb1 <= {W{1'b0}};
		t0  <= 3'd0;
		t1  <= 3'd0;
		t2  <= 3'd0;
		vo  <= 1'b0;
		mo  <= 1'b0;
		xo  <= 16'd0;
		yo  <= 16'd0;
	end
	else if(v == 1'b1)
	begin
		lb0 <= {b,  lb0[W-1:1]};
		lb1 <= {p1, lb1[W-1:1]};
		t0  <= {b,  t0[2:1]};
		t1  <= {p1, t1[2:1]};
		t2  <= {p2, t2[2:1]};
		vo  <= 1'b1;
		mo  <= m_bit;
		xo  <= xo_n;
		yo  <= yo_n;
	end
	else
		vo <= 1'b0;
end

endmodule

// ------------------------------------------------------------
// morph —— 开运算 + 边界有效位
//
// 两级串联：腐蚀(u_erode) → 膨胀(u_dilate)。
//
// 【全宽流水与末端屏蔽】
//   两级内部都不改 v（一直全宽），只在出口统一给有效位：
//   第二级的窗口要取第一级输出列的 x'-3..x'-1（x' = 第一级输出坐标），
//   而第一级的数据只有 x' >= 1 才成立（第一级窗口完整条件 x1 >= 3，
//   输出 x1-2 >= 1）。推到出口坐标 (xo = x1-4) 上，要求
//       xo >= 2  且  yo >= 2
//   等价于 输入 x1 >= 6、y1 >= 4。于是出口有效区 = 列 2..371、行 2..237，
//   上下左右各丢 2 像素（376x240 里丢 2 像素，投影上完全看不出来）。
//
//   出口把无效区域的前景位也一并清 0，这样下游（projection）只按 m_valid
//   计数就够了，不必自己再判一遍边界。
// ------------------------------------------------------------
module morph
(
	input                       clk,
	input                       rst_n,
	// ---- 来自 m2_engine 的前景流 ----
	input                       fg_valid,
	input                       fg,
	input[15:0]                 fg_x,
	input[15:0]                 fg_y,
	// ---- 形态学输出流 ----
	output                      m_valid,
	output                      m_fg,
	output[15:0]                m_x,
	output[15:0]                m_y
);

wire       v1;
wire       b1;
wire[15:0] x1;
wire[15:0] y1;

wire       v2;
wire       b2;
wire[15:0] x2;
wire[15:0] y2;

morph3x3 #(1) u_erode
(
	.clk   (clk),
	.rst_n (rst_n),
	.v     (fg_valid),
	.b     (fg),
	.x     (fg_x),
	.y     (fg_y),
	.vo    (v1),
	.mo    (b1),
	.xo    (x1),
	.yo    (y1)
);

morph3x3 #(0) u_dilate
(
	.clk   (clk),
	.rst_n (rst_n),
	.v     (v1),
	.b     (b1),
	.x     (x1),
	.y     (y1),
	.vo    (v2),
	.mo    (b2),
	.xo    (x2),
	.yo    (y2)
);

wire in_region = (x2 >= 16'd2) && (y2 >= 16'd2);

assign m_valid = v2 & in_region;
assign m_fg    = in_region ? b2 : 1'b0;
assign m_x     = x2;
assign m_y     = y2;

endmodule
