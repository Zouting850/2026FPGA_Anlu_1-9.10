# Pass A -- takeover latency, swept over the whole frame
# ---------------------------------------------------------------------------
def pass_a(res, verbose):
    print("=" * 78)
    print("A. Takeover latency: decision -> first alarm frame, every phase")
    print("=" * 78)

    bound = FRAME_VCLKS + CDC_VCLKS + 1
    limit = FRAME_VCLKS * 3 + 50
    worst, worst_at, failures, frames_over = 0, None, [], 0
    phases = range(0, FRAME_VCLKS, 5)

    for phase in phases:
        s = System()
        s.settle_vid(phase)
        s.send_cmd("ALRM 1")
        dv = s.run_until(lambda x: x.st['ef_act'] == 1, limit)
        if dv is None:
            failures.append((phase, 'never'))
            continue
        frames = s.frame_idx - (s.decide_frame if s.decide_frame is not None
                                else s.frame_idx)
        if dv > worst:
            worst, worst_at = dv, phase
        if frames > 1:
            frames_over += 1
        if verbose:
            print("      phase %3d -> %3d video clk, %d frame boundaries"
                  % (phase, dv, frames))

    res.add(not failures, "alarm reaches the panel from every frame phase",
            "%d phases swept, %d never took over" % (len(list(phases)),
                                                      len(failures)))
    res.add(worst <= bound,
            "worst-case latency <= one frame + CDC depth",
            "max %d video clk at phase %s, bound %d (FRAME_VCLKS=%d + CDC=%d)"
            % (worst, worst_at, bound, FRAME_VCLKS, CDC_VCLKS))
    res.add(frames_over == 0,
            "never more than one frame boundary is crossed",
            "%d phases needed 2+ frames" % frames_over)

    # The audio/buzzer path skips the frame-atomic stage and must lead.
    a = System()
    a.send_cmd("ALRM 1")
    da = a.run_until(lambda x: x.st['emg_act_v1'] == 1, limit)
    v = System()
    v.send_cmd("ALRM 1")
    dv = v.run_until(lambda x: x.st['ef_act'] == 1, limit)
    res.add(da is not None and dv is not None and da <= dv and dv - da >= 1,
            "audio/buzzer path leads the pixel path",
            "audio %d video clk, pixels %d (pixels wait for no tearing)"
            % (da, dv))

    worst_ms = float(FRAME_VCLKS + CDC_VCLKS) / FRAME_VCLKS * FRAME_MS
    res.add(abs(FRAME_MS - 16.80) < 0.02 and worst_ms < 2.0 * FRAME_MS,
            "headline number is the shipped 640x480p60 geometry",
            "%dx%d @ %.3f MHz = %.2f ms/frame; worst takeover %.2f ms"
            % (H_TOTAL, V_TOTAL, PIXEL_CLK_MHZ, FRAME_MS, worst_ms))


