#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
sim_emergency.py -- cycle-accurate model of the emergency-takeover path.

Why this exists
---------------
There is no Verilog simulator on this machine (project memory
"no-verilog-simulator-use-python-models"), so the emergency terminal's control
logic is pinned down here, in Python, before any of it goes near a 10-minute TD
build and a hand-flash. This models the exact non-blocking behaviour of the three
clock domains the feature touches:

  * clk (50 MHz)      -- emergency_ctrl: 3FF pin synchronisers, the asymmetric
                         (immediate-set / timed-release) debouncer, the
                         three-candidate priority resolver, the {active,type}
                         state register and its companion toggle, the VOLM latch,
                         and the burn-in sequencer.
                     -- top's merge point: every non-ALRM/VOLM command strobe is
                         ANDed with ~hold while the alarm is up.
  * sd_card_clk       -- hold crosses on a bare 2FF and gates the PHYSICAL
   (100 MHz)            key1/key2 inputs, so the carousel cannot wander under
                         the alarm and resumes on the same picture after release.
  * video_clk         -- hold crosses two ways on purpose:
   (25 MHz)              - active level, bare 2FF  -> audio + buzzer (immediate)
                          - {active,type}, data+toggle -> staging register, then
                            a frame-atomic latch at video_frame_start -> overlay.
                         Plus the 2FF on vol_level and the 4-way audio mux.

Frame timing is generated by a shrinkable divider (FRAME_VCLKS); the real frame
is 800*525 = 420,000 video clocks. The frame-atomic latch is a bare
`if (video_frame_start)` whose correctness does not depend on frame length, so
shrinking it is the same legitimate speed-up sim_uart_ctrl.py applies to
CLKS_PER_BIT -- and Pass A converts the structural result back to milliseconds
from the real geometry. Pass F likewise re-runs the release window at the SHIPPED
CLK_FREQ_HZ / RELEASE_MS so the constant that goes on the board is the one proved.

What it verifies (passes A-I)
-----------------------------
  A. Takeover latency. Sweeping the trigger across every phase of the frame, the
     overlay's frame-atomic output follows the clk-domain decision within
     (one frame + CDC depth) and never takes two. The audio/buzzer path, which
     takes the bare 2FF instead, must be strictly faster -- it has no tearing to
     avoid. Converted to the shipped 16.80 ms/frame number.
  B. Single stage, forced, explicit release. The alarm survives 50 idle frames
     (no timeout -- a self-clearing fire alarm is a liability), ALRM 0 is the only
     command release, a second ALRM n replaces rather than nests, and the release
     lands on exactly one frame boundary.
  C. Command freeze at the merge point. All eleven other commands while the alarm
     is up change NOTHING in the clk latches or the sd/video crossings, and the
     SAME commands with no alarm do change them, so the check is not vacuous.
     ALRM and VOLM stay live -- ALRM is the alarm's own control, VOLM is a user's
     right. Physical key1 is swallowed under the alarm and works without it.
  D. Multi-source fusion and fail-safe release. Three requestors (command, T1
     manual, T2 sensor). Releasing any one must NOT drop the alarm while another
     still asks -- release is an AND, not last-writer-wins. Type priority
     火警(1) > 疏散(2) > 通用(3) is the numeric minimum of the live candidates,
     so escalation can only lower the code, and de-escalation is refused while a
     higher requestor holds. Escalation never re-times the alarm.
  E. Asymmetric debounce. Make arms in a few clk; a 19.99 ms break does not
     clear, a clean one does. NEGATIVE CONTROL: a symmetric debouncer pushes the
     make past one frame, which is exactly the headline property it would break.
  F. Real timing: the shipped 20 ms release window at 50 MHz.
  G. Volume and the siren bypass. VOLM 2/1/0 is a 0/-12 dB/-inf digital gain on
     the two signage sources; the siren bypasses it, because a muted fire alarm
     is worse than no alarm. The alarm select must not appear in audio_valid --
     checked against the shipped RTL text, because audio_arc_calculate counts 48
     valids per CTS and a gap loses HDMI audio lock.
  H. The one-line retreat. EMERGENCY_ENABLE=0 makes the whole System
     indistinguishable from one with no emergency_ctrl, and does so on the DATA
     as well as the strobes -- structural check over the RTL text, because this
     project has already been caught once by a retreat that only gated a strobe
     (led[3]) and so left the instance a load and out of the area report never.
  I. Siren synthesiser arithmetic: 32-bit phase-accumulator frequencies land
     within 1 Hz of target, and the accumulator is advanced, never reloaded, so
     a frequency swap cannot step the waveform.

Honest limits
-------------
  * The pixel CONTENT of alarm_overlay (glyphs, travelling chevrons, hazard
    stripes) is not modelled here. This proves the enable / type / latency /
    gating / CDC contract that FEEDS it. The raster is evidence-backed by
    tools/gen_alarm_font.py's preview PNGs and
    tools/check_alarm_font_transcription.py, the same split marquee_overlay uses.
  * sd_card_bmp's internals (its own key debouncer, the IMGX img_loaded_count
    gate, the carousel second counter) are not modelled end-to-end. Pass C
    proves the values feeding those gates are frozen, which is what a snapshot
    comparison can actually check; `next_press_sd` here stands in for "key1's
    edge reached sd_card_bmp", not for its debounce maths.
  * The siren waveform is modelled as its amplitude/frequency contract, not as
    the full accumulator. What could silently break the build is the valid
    stream, and that is what Pass G measures against the RTL.

Usage
-----
    python tools/sim_emergency.py            # all passes, PASS/FAIL per check
    python tools/sim_emergency.py --verbose
Exit code 0 on success, 1 if any check fails.
"""

