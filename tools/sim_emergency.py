# Pass D -- three requestors, fail-safe release AND, type priority
# ---------------------------------------------------------------------------
def pass_d(res, verbose):
    print("=" * 78)
    print("D. Multi-source fusion, fail-safe release, type priority")
    print("=" * 78)

    s = System()
    s.send_cmd("ALRM 3")
    s.settle(30)
    s.pin_aut = 0
    s.settle(30)
    res.add((s.st['emg_state'] & 3) == TYPE_FIRE,
            "T2 closed while a 通用 alarm is up escalates to 火警",
            "type=%d" % (s.st['emg_state'] & 3))
    s.send_cmd("ALRM 0")
    s.settle(60)
    res.add(s.st['emg_state'] != 0,
            "ALRM 0 alone does NOT clear a held T2 contact",
            "state=%d -- release is an AND over the requestors"
            % s.st['emg_state'])
    s.pin_aut = 1
    s.settle(s.cnt_max + 20)
    res.add(s.st['emg_state'] == 0,
            "releasing the last live requestor clears the alarm",
            "state=%d after the release window" % s.st['emg_state'])

    # Columns are written in the order a reader reasons in: which CONTACTS ARE
    # CLOSED. The pins themselves are active low (PULLUP, a dry contact pulls the
    # line to GND), so each flag is inverted on the way in -- mixing those two up
    # is what made an earlier revision of this table expect 疏散 from a board whose
    # fire contact was held shut.
    cases = [
        (TYPE_GEN, 0, 0, TYPE_GEN, "command only"),
        (TYPE_GEN, 0, 1, TYPE_FIRE, "T2 fire beats a 通用 command"),
        (TYPE_GEN, 1, 0, TYPE_EVAC, "T1 evac beats a 通用 command"),
        (TYPE_GEN, 1, 1, TYPE_FIRE, "T1+T2, fire wins"),
        (TYPE_FIRE, 1, 0, TYPE_FIRE, "command fire, T1 held"),
        (TYPE_EVAC, 0, 1, TYPE_FIRE, "a held T2 fire outranks ALRM 2"),
    ]
    for cmd_t, t1, t2, want, why in cases:
        s = System()
        s.pin_man = 0 if t1 else 1
        s.pin_aut = 0 if t2 else 1
        s.send_cmd("ALRM %d" % cmd_t)
        s.settle(40)
        res.add((s.st['emg_state'] & 3) == want,
                "priority: %s -> type %d" % (why, want),
                "got %d (cmd=%d T1 closed=%d T2 closed=%d)"
                % (s.st['emg_state'] & 3, cmd_t, t1, t2))

    s = System()
    s.send_cmd("ALRM 3")
    s.settle(40)
    s.settle_vid(FRAME_VCLKS * 3)
    frame_at_up = s.frame_idx
    s.send_cmd("ALRM 1")
    s.settle(20)
    res.add((s.st['emg_state'] & 3) == TYPE_FIRE and s.st['ef_act'] == 1
            and s.frame_idx - frame_at_up <= 1,
            "escalation 通用->火警 changes content, never re-times",
            "type=%d, still active, %d frames elapsed"
            % (s.st['emg_state'] & 3, s.frame_idx - frame_at_up))

    s = System()
    s.pin_aut = 0
    s.settle(40)
    up = s.st['emg_state']
    s.send_cmd("ALRM 3")
    s.settle(60)
    res.add((up & 3) == TYPE_FIRE and (s.st['emg_state'] & 3) == TYPE_FIRE,
            "ALRM 3 cannot de-escalate a live T2 fire contact",
            "type stays %d" % (s.st['emg_state'] & 3))

    # Both hardlines, one type each: the pin identity fixes the semantics.
    s = System()
    s.pin_man = 0
    s.settle(40)
    t_man = s.st['emg_state'] & 3
    s2 = System()
    s2.pin_aut = 0
    s2.settle(40)
    t_aut = s2.st['emg_state'] & 3
    res.add(t_man == TYPE_EVAC and t_aut == TYPE_FIRE,
            "T1 defaults to 疏散, T2 to 火警",
            "T1->%d T2->%d (both are parameters)" % (t_man, t_aut))


