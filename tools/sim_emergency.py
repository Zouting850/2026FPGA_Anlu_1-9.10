def _read(*rel):
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.abspath(os.path.join(here, *rel))
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return f.read()
    except IOError:
        return ""


def _find_assign(text, lhs):
    for line in text.splitlines():
        if ("assign %s" % lhs) in line.replace("  ", " "):
            return line
    for line in text.splitlines():
        if line.strip().startswith(lhs) and "=" in line and "assign" not in line:
            return line
    return ""


def _strip_comments(text):
    """Blank out // and /* */ comments, preserving offsets and newlines.

    Offsets are the point: the callers still report line-based findings, and a
    stripper that shortened the text would desynchronise them from the file.
    """
    out = []
    i, n = 0, len(text)
    in_str = False
    while i < n:
        c = text[i]
        two = text[i:i + 2]
        if in_str:
            out.append(c)
            if c == '"':
                in_str = False
            i += 1
        elif c == '"':
            in_str = True
            out.append(c)
            i += 1
        elif two == "//":
            while i < n and text[i] != "\n":
                out.append(" ")
                i += 1
        elif two == "/*":
            while i < n and text[i:i + 2] != "*/":
                out.append("\n" if text[i] == "\n" else " ")
                i += 1
            out.append("  ")
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def _instance_src(text, inst):
    """One instance's port map, from its `( ` to the closing `);`. Empty string if
    the instance is not there at all, so callers can write `bool(smap) and ...`.

    Searched in comment-free text on purpose: the top's own prose names instances
    -- `u_alarm_siren (the whole scope disappears, not just the instance)` sits a
    hundred lines above the real one -- and a plain find returns a slice of that
    sentence instead of a port map, which reads as missing wires and a stray
    frame-latched net in a design whose wiring is fine.
    """
    code = _strip_comments(text)
    i = code.find(inst + " (")
    if i < 0:
        return ""
    j = code.find(");", i)
    return code[i:j] if j > 0 else ""


def _param_src(text, mod, inst):
    """One instance's PARAMETER list, i.e. the `mod #(...)` before `) inst (`.

    The companion of _instance_src, and needed because the two halves do not
    overlap: an instance's port map starts at the paren after its name, which is
    on the far side of the parameter block's closing paren. Every override that
    matters at build time -- BURN_SEC, EMERGENCY_ENABLE, TONE_HZ -- lives here, so
    a check that reads only the port map silently cannot see it.
    """
    code = _strip_comments(text)
    i = code.find(inst + " (")
    if i < 0:
        return ""
    j = code.rfind(mod + " #(", 0, i)
    return code[j:i] if j >= 0 else ""


