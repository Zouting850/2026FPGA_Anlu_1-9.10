def _valid_is_constant(src):
    """True when every assignment to O_audio_valid in `src` drives a constant.

    What starves audio_arc_calculate's 48-valids-per-CTS count is a valid written
    from anything that can go away -- its own enable, a mute, a FIFO-not-empty
    flag. Constants are safe: the reset and the per-cycle default clear are two of
    them in audio_pcm_player.v's house pattern, and the tick assertion is the 1'b1.
    """
    lines = [l for l in src.splitlines()
             if 'O_audio_valid' in l and '<=' in l
             and not l.strip().startswith('//')]
    consts = [l for l in lines if re.search(r"<=\s*1'b[01]\s*;", l)]
    return bool(lines) and len(consts) == len(lines) and \
           any(re.search(r"<=\s*1'b1\s*;", l) for l in lines)


def _layer_is_generated(src):
    """True when the alarm overlay instance sits inside a generate guarded by
    EMERGENCY_ENABLE, and the disabled branch hands the pixels straight through."""
    m = re.search(r"if\s*\(EMERGENCY_ENABLE\)\s*begin[^:]*:\s*\w+(.*?)endgenerate",
                  src, re.S)
    return bool(m) and 'u_alarm_overlay' in m.group(1) \
        and 'assign vout_data_alarm = vout_data;' in m.group(1)


def _mem_decls(src):
    """Lines that would infer a block RAM: a 2-D memory declaration, or a literal
    BRAM attribute. NOT the substring 'ram' -- that matches 'parameter' and
    'localparam', which every module in this project has, and a check that can
    never pass is not a strict check."""
    decl = re.compile(r'\b(?:reg|wire)\b[^;=\n]*\[[^\]]*\]'
                      r'\s*[A-Za-z_]\w*\s*\[[^\]]*\]')
    return [l for l in src.splitlines()
            if not l.strip().startswith('//')
            and (re.search(r'\bBRAM\b', l) or decl.search(l))]


