import os
import re
import sys

# ---------------------------------------------------------------------------
# Clock geometry (ns). Offsets guarantee no two posedges ever coincide, so every
# CDC sample in here is genuinely asynchronous instead of luckily aligned.
# ---------------------------------------------------------------------------
CLK_PERIOD = 20        # 50 MHz
SD_PERIOD = 10         # 100 MHz
VID_PERIOD = 40        # 25 MHz
CLK_OFF = 0
SD_OFF = 3
VID_OFF = 7            # never 0 or 20 mod 40, so video and clk never coincide

FRAME_VCLKS = 200      # shrunken frame; see "Honest limits"
CDC_VCLKS = 4          # 3FF on the toggle + the clock that commits the staging
LEVEL_VCLKS = 2        # bare 2FF feeding the audio/buzzer mux

H_TOTAL = 800
V_TOTAL = 525
PIXEL_CLK_MHZ = 25.0
FRAME_MS = H_TOTAL * V_TOTAL / (PIXEL_CLK_MHZ * 1000.0)      # 16.80 ms

# The debouncer and the burn-in sequencer are pure functions of CLK_FREQ_HZ, so
# passing a smaller ticks-per-ms is the same parameter-shrink argument, and Pass
# F re-runs the shipped value.
TICKS_PER_MS_FAST = 50                  # 1000x shrunk
TICKS_PER_MS_REAL = 50_000              # 50 MHz / 1000

TYPE_NONE, TYPE_FIRE, TYPE_EVAC, TYPE_GEN = 0, 1, 2, 3
TYPE_GENERAL = TYPE_GEN                   # the name alarm_siren.v uses for code 3
VOL_FULL, VOL_MID, VOL_MUTE = 2, 1, 0

MANUAL_TYPE = TYPE_EVAC                 # T1 manual call point orders evacuation
AUTO_TYPE = TYPE_FIRE                   # T2 smoke/heat contact reports a fire

TONE_LEFT = 0x300000
MUS_LEFT = 0x400000
SIREN_LEFT = 0x700000

# Commands that must freeze while the alarm holds. ALRM/VOLM are the deliberate
# exceptions, exercised separately in Pass C.
FREEZE_CMDS = ["NEXT", "AUTO", "BRUP", "BRGT 0", "MODE 3", "MARQ 0", "IMGX 2",
               "FILT 5", "FONT 1", "MUSC 1", "SPED 5"]

# Everything the emergency path is allowed to move, plus the pre-existing latches
# it is not. One comparable tuple, so "frozen" and "retreated" are both equality
# proofs rather than hand-written expectation lists.
STATE_KEYS = ('req_cmd', 'mlvl', 'alvl', 'emg_state', 'emg_tgl', 'vol_level',
              'burn_cnt', 'burn_on', 'burn_type', 'burn_req', 'burn_req_v',
              'brightness', 'mode_ovr_val', 'mode_ovr_en', 'marq_ovr_val',
              'marq_ovr_en', 'filt_val', 'font_val', 'music_en',
              'img_sel_lat', 'speed_lat', 'next_tgl', 'auto_tgl', 'img_tgl',
              'spd_tgl', 'hold_s0', 'hold_sd', 'key1_seen', 'next_press_sd',
              'emg_act_s0', 'emg_act_v1', 'emg_type_s0', 'emg_type_v1',
              'etgl_s0', 'etgl_s1', 'etgl_s2',
              'estg_act', 'estg_type', 'ef_act', 'ef_type',
              'vol_s0', 'vol_v1')

# The signage state that predates the feature. A realistic retreat barrage below
# has to include legitimate NEXT/MODE/BRGT traffic, so the "the feature is gone"
# equality can only be about the rest -- and derived rather than hand-listed, so
# a new register cannot silently fall on the wrong side of the split.
PREEXISTING_KEYS = ('brightness', 'mode_ovr_val', 'mode_ovr_en', 'marq_ovr_val',
                    'marq_ovr_en', 'filt_val', 'font_val', 'music_en',
                    'img_sel_lat', 'speed_lat', 'next_tgl', 'auto_tgl',
                    'img_tgl', 'spd_tgl', 'key1_seen', 'next_press_sd')
EMG_KEYS = tuple(k for k in STATE_KEYS if k not in PREEXISTING_KEYS)


def frame_bytes(cmd_str):
    """Wire bytes of a TJC framed command: ASCII payload + three 0xFF."""
    return [ord(c) for c in cmd_str] + [0xFF, 0xFF, 0xFF]


def parse_cmd(byte_list):
    """
    Stand-in for uart_screen_ctrl's dispatch: framed bytes -> the strobe/value
    pair it fires. A direct transcription of the RTL's guards, so a typo here
    cannot make a check pass that the real parser would reject. Note the two
    invariants this file has to obey rather than invent:

      * the keyword is exactly FOUR payload bytes, because the RTL dispatches on
        `case ({c0, c1, c2, c3})`. That is why the alarm commands are ALRM and
        VOLM rather than the shorter EMG and VOL a reviewer would expect -- a
        three-letter keyword makes clen 5 and no arm of the case matches.
      * payload[4] is the mandatory space and payload[5] the argument digit,
        because the RTL checks `clen == 6 && c4 == " " && <c5 in range>`.

    sim_uart_ctrl.py already proves this parser byte-for-byte against the wire;
    duplicating that proof is not this file's job.
    """
    payload = bytes(b for b in byte_list if b != 0xFF)
    kw = payload[:4].decode('ascii', 'replace')
    clen = len(payload)
    arg = payload[5] if clen == 6 and payload[4] == 0x20 else None
    out = {}

    def digit(lo, hi):
        return arg is not None and lo <= arg <= hi

    if clen == 4:
        for k, cmd in (('NEXT', 'cmd_next_pulse'), ('AUTO', 'cmd_auto_pulse'),
                       ('BRUP', 'cmd_bright_cycle_pulse')):
            if kw == k:
                out[cmd] = 1
    elif clen == 6 and kw == 'BRGT' and digit(ord('0'), ord('4')):
        out['cmd_bright_set'] = arg - 0x30
        out['cmd_bright_set_v'] = 1
    elif clen == 6 and kw == 'MODE' and digit(ord('0'), ord('9')):
        out['cmd_mode'] = arg - 0x30
        out['cmd_mode_set'] = 1
    elif clen == 6 and kw == 'MARQ' and digit(ord('0'), ord('1')):
        out['cmd_marquee'] = arg - 0x30
        out['cmd_marquee_set'] = 1
    elif clen == 6 and kw == 'IMGX' and digit(ord('1'), ord('4')):
        out['cmd_img_sel'] = arg - 0x30 - 1
        out['cmd_img_sel_set'] = 1
    elif clen == 6 and kw == 'FILT' and digit(ord('0'), ord('9')):
        out['cmd_filt'] = arg - 0x30
        out['cmd_filt_set'] = 1
    elif clen == 6 and kw == 'FONT' and digit(ord('0'), ord('1')):
        out['cmd_font'] = arg - 0x30
        out['cmd_font_set'] = 1
    elif clen == 6 and kw == 'MUSC' and digit(ord('0'), ord('1')):
        out['cmd_audio'] = arg - 0x30
        out['cmd_audio_set'] = 1
    elif clen == 6 and kw == 'SPED' and digit(ord('1'), ord('8')):
        out['cmd_speed'] = arg - 0x30
        out['cmd_speed_set'] = 1
    elif clen == 6 and kw == 'ALRM' and digit(ord('0'), ord('3')):
        out['cmd_emg'] = arg - 0x30
        out['cmd_emg_set'] = 1
    elif clen == 6 and kw == 'VOLM' and digit(ord('0'), ord('2')):
        out['cmd_vol'] = arg - 0x30
        out['cmd_vol_set'] = 1
    return out


class System(object):
    """Mirrors every register the emergency path adds, in all three domains."""

    def __init__(self, emergency_enable=1, release_ms=20,
                 ticks_per_ms=TICKS_PER_MS_FAST, burn_sec=0,
                 manual_type=MANUAL_TYPE, auto_type=AUTO_TYPE,
                 vol_default=VOL_FULL, symmetric=0, burn_stuck=0):
        self.emergency_enable = emergency_enable
        self.release_ms = release_ms
        self.ticks_per_ms = ticks_per_ms
        self.burn_sec = burn_sec
        self.manual_type = manual_type
        self.auto_type = auto_type
        # NEGATIVE CONTROL ONLY: debounce the make the same as the break. Nothing
        # on the happy path constructs a System with this set. It changes how long
        # the SET waits, not how long the window is -- doubling cnt_max instead
        # would leave the make instant and the negative control vacuous.
        self.symmetric = symmetric
        self.burn_stuck = burn_stuck
        self.cnt_max = release_ms * ticks_per_ms

        self.t = 0                    # merged time axis, ns
        self.clk_n = 0
        self.sd_n = 0
        self.vid_n = 0
        self.frame_idx = 0
        self.decide_frame = None      # frame index when emg_state first went live

        # injectable primary inputs
        self.rx = []                  # pending UART bytes, consumed one per clk
        self.ffcnt = 0                # consecutive 0xFF, as the RTL counts it
        self.pend = b''               # accumulated payload bytes
        self.pin_man = 1              # idle high: PULLUP, dry contact pulls to GND
        self.pin_aut = 1
        self.key1 = 0
        self.key2 = 0
        self.tone_left = TONE_LEFT
        self.mus_left = MUS_LEFT

        s = {}
        for k in STATE_KEYS:
            s[k] = 0
        # Registers that exist in the RTL but are deliberately left out of
        # STATE_KEYS: the two release counters and the frame generator. They are
        # phase state, not observable behaviour, so letting them differ is what
        # keeps the snapshot equalities in Passes C and H about the feature and
        # not about when each System happened to be constructed.
        for k in ('mcnt', 'acnt', 'vid_div', 'frame_start'):
            s[k] = 0
        # idle-high pin synchronisers, and the pre-existing reset values top uses
        for k in ('ms0', 'ms1', 'ms2', 'as0', 'as1', 'as2', 'vs', 'vs_d'):
            s[k] = 1
        s['brightness'] = 2
        s['marq_ovr_val'] = 1
        s['speed_lat'] = 1
        s['vol_level'] = vol_default
        s['vol_s0'] = vol_default
        s['vol_v1'] = vol_default
        s['burn_type'] = TYPE_FIRE
        self.st = s

        # clk-domain command wires: pure functions of the parser, recomputed each
        # edge, seeded here only so the keys exist.
        for k in ('cmd_next_pulse', 'cmd_auto_pulse', 'cmd_bright_cycle_pulse',
                  'cmd_bright_set_v', 'cmd_mode_set', 'cmd_marquee_set',
                  'cmd_img_sel_set', 'cmd_filt_set', 'cmd_font_set',
                  'cmd_audio_set', 'cmd_speed_set', 'cmd_emg_set',
                  'cmd_vol_set', 'cmd_bright_set', 'cmd_mode', 'cmd_marquee',
                  'cmd_img_sel', 'cmd_filt', 'cmd_font', 'cmd_audio',
                  'cmd_speed', 'cmd_emg', 'cmd_vol'):
            s[k] = 0

        self.log = {'emg_up_clk': None, 'emg_down_clk': None}

    # -- combinational mirrors of the RTL's assigns ---------------------
    @staticmethod
    def min_live(a, b):
        """Lowest non-zero code wins, which is what makes 1 > 2 > 3 arithmetic."""
        if a == 0:
            return b
        if b == 0:
            return a
        return a if a < b else b

    def resolved(self):
        """The (active, type) the state register loads on this edge."""
        s = self.st
        typ = 0
        if s['alvl']:
            typ = self.min_live(typ, self.auto_type)
        if s['mlvl']:
            typ = self.min_live(typ, self.manual_type)
        if s['req_cmd']:
            typ = self.min_live(typ, s['req_cmd'])
        return (1 if typ else 0), typ

    def hold(self):
        """top's `wire hold = EMERGENCY_ENABLE & emg_state[2]`."""
        return self.emergency_enable & ((self.st['emg_state'] >> 2) & 1)

    def cmd_gate(self):
        return 1 - self.hold()

    def key_gate(self):
        return 1 - (self.emergency_enable & self.st['hold_sd'])

    def siren_sel(self):
        """The ONLY consumer of the fast video_clk crossing: alarm_siren's I_en."""
        return self.emergency_enable & self.st['emg_act_v1']

    def buzzer_on(self):
        """buzzer_beep is in clk, not video_clk: it never crosses, so it is exactly
        the hold level. Top's 2FF pair is for the siren, which has to be muxed into
        a video_clk PCM stream; a horn on a pin has no such reason to wait."""
        return self.hold()

    def audio_src_left(self):
        """4-way priority: siren > (WAV | tone) x gain. See top's assign."""
        if self.siren_sel():
            return SIREN_LEFT
        raw = self.mus_left if self.st['music_en'] else self.tone_left
        vol = self.st['vol_v1'] if self.emergency_enable else VOL_FULL
        if vol == VOL_MUTE:
            return 0
        if vol == VOL_MID:
            return raw >> 2
        return raw

    def audio_valid(self):
        """A constant 1. top's expression does name selects, including the alarm's,
        and that is still safe only because EVERY arm emits an unbroken 48 kHz
        stream -- which is what Pass I checks alarm_siren.v for, and what would
        break if anyone ever gated a valid by its own enable or by a mute."""
        return 1

    def snapshot(self):
        return tuple(self.st[k] for k in STATE_KEYS)

    def emg_snapshot(self):
        """Only what the feature can move -- see PREEXISTING_KEYS/EMG_KEYS."""
        return tuple(self.st[k] for k in EMG_KEYS)

    # -- one merged ns step ---------------------------------------------
    def tick(self):
        t = self.t
        self.t += 1
        s = self.st
        old = dict(s)                # non-blocking: every RHS reads pre-edge state

        do_clk = (t % CLK_PERIOD) == CLK_OFF
        do_sd = (t % SD_PERIOD) == SD_OFF
        do_vid = (t % VID_PERIOD) == VID_OFF

        if do_clk:
            self.clk_n += 1
            strobes = self._consume_byte()
            for k in ('cmd_next_pulse', 'cmd_auto_pulse',
                      'cmd_bright_cycle_pulse', 'cmd_bright_set_v',
                      'cmd_mode_set', 'cmd_marquee_set', 'cmd_img_sel_set',
                      'cmd_filt_set', 'cmd_font_set', 'cmd_audio_set',
                      'cmd_speed_set', 'cmd_emg_set', 'cmd_vol_set'):
                s[k] = 0
            gate = self.cmd_gate()
            # Only the strobes need the freeze: every consumer writes its latch on
            # a strobe, so the value buses simply go unused while held.
            for k in ('cmd_next_pulse', 'cmd_auto_pulse',
                      'cmd_bright_cycle_pulse', 'cmd_bright_set_v',
                      'cmd_mode_set', 'cmd_marquee_set', 'cmd_img_sel_set',
                      'cmd_filt_set', 'cmd_font_set', 'cmd_audio_set',
                      'cmd_speed_set'):
                s[k] = strobes.get(k, 0) * gate
            s['cmd_emg_set'] = strobes.get('cmd_emg_set', 0)
            s['cmd_vol_set'] = strobes.get('cmd_vol_set', 0)
            for v in ('cmd_bright_set', 'cmd_mode', 'cmd_marquee', 'cmd_img_sel',
                      'cmd_filt', 'cmd_font', 'cmd_audio', 'cmd_speed',
                      'cmd_emg', 'cmd_vol'):
                if v in strobes:
                    s[v] = strobes[v]

            self._clk_domain(old)

        if do_sd:
            self.sd_n += 1
            s['hold_s0'] = self.hold()
            s['hold_sd'] = old['hold_s0']
            k1 = self.key1 & self.key_gate()
            s['key1_seen'] = k1
            if k1 and not old['key1_seen']:
                s['next_press_sd'] = old['next_press_sd'] + 1

        if do_vid:
            self.vid_n += 1
            self._vid_domain(old)

    def _consume_byte(self):
        """Feed one UART byte per clk edge through the framed-parser stand-in."""
        if not self.rx:
            return {}
        b, self.rx = self.rx[0], self.rx[1:]
        if b == 0xFF:
            self.ffcnt += 1
            if self.ffcnt == 3 and self.pend:
                out = parse_cmd(self.pend)
                self.pend = b''
                self.ffcnt = 0
                return out
            return {}
        self.ffcnt = 0
        self.pend += bytes([b])
        return {}

    def _debounce(self, old, sync_key, lvl_key, cnt_key):
        """
        One hard-line input: a dry contact that pulls to GND when it fires, so the
        synced 0 is the alarm.

        Asymmetric on purpose. SET follows the 3FF-synced level with no wait, so
        the anti-chatter filter can never delay the thing it exists to filter --
        that is what keeps the <=1 frame headline true on the wire. RELEASE needs
        cnt_max consecutive inactive samples, because a contact that opens and
        slams shut again (a hand on a Dupont line, a chattering relay) must not
        end an alarm. The counter re-arms on every active sample, so a bounce
        restarts the countdown from the far end.

        symmetric=1 is the negative control Pass E runs and nothing else: it holds
        the SET for the same window, which on hardware costs 20 ms against a
        16.8 ms frame.
        """
        s = self.st
        active = (old[sync_key] == 0)
        if not active:
            if old[lvl_key]:
                if old[cnt_key] == 0:
                    s[lvl_key] = 0
                else:
                    s[cnt_key] = old[cnt_key] - 1
            elif self.symmetric:
                s[cnt_key] = 0
        elif not self.symmetric:
            s[lvl_key] = 1
            s[cnt_key] = self.cnt_max
        elif old[cnt_key] >= self.cnt_max:
            s[lvl_key] = 1
        else:
            s[cnt_key] = old[cnt_key] + 1

    def _clk_domain(self, old):
        s = self.st
        # 3FF pin synchronisers
        s['ms0'] = self.pin_man
        s['as0'] = self.pin_aut
        s['ms1'], s['ms2'] = old['ms0'], old['ms1']
        s['as1'], s['as2'] = old['as0'], old['as1']

        # One unit, two instances: the two hard lines differ only in which register
        # names they own, so they share a helper rather than being pasted twice.
        self._debounce(old, 'ms2', 'mlvl', 'mcnt')
        self._debounce(old, 'as2', 'alvl', 'acnt')

        # ---- the req_cmd load, the RTL's second always block ------------------
        # Two sources, one mux, operator first. Not a race in either direction:
        # the sequencer publishes a value plus a one-cycle valid, so a coincident
        # ALRM simply wins the mux and the sequencer keeps its own time.
        if self.emergency_enable and (old['cmd_emg_set'] or old['burn_req_v']):
            s['req_cmd'] = (old['cmd_emg'] if old['cmd_emg_set']
                            else old['burn_req'])

        # ---- burn-in sequencer, the RTL's first always block ------------------
        if self.emergency_enable and self.burn_sec:
            wrap_at = self.burn_sec * 1000 * self.ticks_per_ms
            s['burn_req_v'] = 0
            if old['burn_cnt'] + 1 >= wrap_at:
                s['burn_cnt'] = 0
                s['burn_on'] = 0 if old['burn_on'] else 1
                nxt = 1 + (old['burn_type'] % 3)          # 1 -> 2 -> 3 -> 1
                if old['burn_on'] == 0:
                    s['burn_type'] = nxt
                    s['burn_req'] = nxt
                else:
                    s['burn_req'] = 0
                s['burn_req_v'] = 1
                # NEGATIVE CONTROL ONLY: drop the release publish and keep the
                # counter running, so the takeover can never be let go.
                if self.burn_stuck and old['burn_on']:
                    s['burn_req_v'] = 0
            else:
                s['burn_cnt'] = old['burn_cnt'] + 1

        if self.emergency_enable and old['cmd_vol_set']:
            s['vol_level'] = old['cmd_vol']

        act, typ = self.resolved()
        new_state = ((act & 1) << 2) | (typ & 3)
        if new_state != old['emg_state']:
            s['emg_tgl'] = 1 - old['emg_tgl']
        s['emg_state'] = new_state
        if old['emg_state'] == 0 and new_state != 0:
            self.log['emg_up_clk'] = self.clk_n
            self.decide_frame = self.frame_idx
        elif old['emg_state'] != 0 and new_state == 0:
            self.log['emg_down_clk'] = self.clk_n

        # ---- the pre-existing latches, written exactly as top writes them ----
        if old['cmd_bright_set_v']:
            s['brightness'] = old['cmd_bright_set']
        elif old['cmd_bright_cycle_pulse']:
            s['brightness'] = (old['brightness'] + 1) % 5
        if old['cmd_mode_set']:
            s['mode_ovr_val'] = old['cmd_mode']
            s['mode_ovr_en'] = 1
        if old['cmd_marquee_set']:
            s['marq_ovr_val'] = old['cmd_marquee']
            s['marq_ovr_en'] = 1
        if old['cmd_filt_set']:
            s['filt_val'] = old['cmd_filt']
        if old['cmd_font_set']:
            s['font_val'] = old['cmd_font']
        if old['cmd_audio_set']:
            s['music_en'] = old['cmd_audio']
        if old['cmd_img_sel_set']:
            s['img_sel_lat'] = old['cmd_img_sel']
            s['img_tgl'] = 1 - old['img_tgl']
        if old['cmd_speed_set']:
            s['speed_lat'] = old['cmd_speed']
            s['spd_tgl'] = 1 - old['spd_tgl']
        if old['cmd_next_pulse']:
            s['next_tgl'] = 1 - old['next_tgl']
        if old['cmd_auto_pulse']:
            s['auto_tgl'] = 1 - old['auto_tgl']

    def _vid_domain(self, old):
        s = self.st
        state = self.st['emg_state']
        s['emg_act_s0'] = (state >> 2) & 1
        s['emg_act_v1'] = old['emg_act_s0']
        s['emg_type_s0'] = state & 3
        s['emg_type_v1'] = old['emg_type_s0']
        s['etgl_s0'] = old['emg_tgl']
        s['etgl_s1'] = old['etgl_s0']
        s['etgl_s2'] = old['etgl_s1']
        s['vol_s0'] = old['vol_level']
        s['vol_v1'] = old['vol_s0']

        if old['etgl_s1'] ^ old['etgl_s2']:
            s['estg_act'] = (state >> 2) & 1
            s['estg_type'] = state & 3

        # frame generator: one vsync falling edge every FRAME_VCLKS video clocks
        s['frame_start'] = 0
        s['vs_d'] = old['vs']
        s['vs'] = 0 if old['vid_div'] >= FRAME_VCLKS - 4 else 1
        if old['vs_d'] and not old['vs']:
            s['frame_start'] = 1
            self.frame_idx += 1
        s['vid_div'] = 0 if old['vid_div'] >= FRAME_VCLKS - 1 else old['vid_div'] + 1
        if s['frame_start']:
            s['ef_act'] = old['estg_act']
            s['ef_type'] = old['estg_type']

    # -- drivers ---------------------------------------------------------
    def send_cmd(self, cmd):
        self.rx.extend(frame_bytes(cmd))

    def settle(self, clk_cycles):
        """Advance at least clk_cycles clk edges, however long it really takes."""
        target = self.clk_n + clk_cycles
        guard = (clk_cycles + 20) * CLK_PERIOD * 2
        for _ in range(guard):
            self.tick()
            if self.clk_n >= target:
                break

    def settle_vid(self, vid_cycles):
        target = self.vid_n + vid_cycles
        guard = (vid_cycles + 20) * VID_PERIOD * 2
        for _ in range(guard):
            self.tick()
            if self.vid_n >= target:
                break

    def run_until(self, pred, limit_vid):
        """
        Step until pred(self) is true. `limit_vid` is in VIDEO CLOCKS -- the same
        unit the return value uses -- so the loop has to convert it to the
        nanosecond axis the model runs on. A frame is FRAME_VCLKS video clocks but
        8400 ns, so passing the limit through unconverted expires the search about
        40x too early and every caller reports "never happened".
        """
        start = self.vid_n
        for _ in range(limit_vid * VID_PERIOD + VID_PERIOD):
            self.tick()
            if pred(self):
                return self.vid_n - start
        return None


class Result(object):
    def __init__(self):
        self.rows = []
        self.failed = 0

    def add(self, ok, name, detail):
        self.rows.append((ok, name, detail))
        if not ok:
            self.failed += 1
        print("  [%s] %-54s %s" % ("PASS" if ok else "FAIL", name, detail))


