# Sound shape: parsed out of the shipped text, so these passes cannot drift
# into checking a design nobody built.
# ---------------------------------------------------------------------------
def _v_num(tok):
    """32'd62634940 / 25_000_000 / 10'd500 -> int. None if it is not a number."""
    tok = (tok or "").strip().replace("_", "")
    m = re.match(r"^\d*'[dDhHoObB]([0-9A-Fa-f]+)$", tok)
    if m:
        base = {'d': 10, 'h': 16, 'o': 8, 'b': 2}[tok[tok.index("'") + 1].lower()]
        return int(m.group(1), base)
    return int(tok) if re.match(r"^\d+$", tok) else None


def _tick_guard_span(code):
    """(start, end) offsets of the `if (W_tick) begin ... end` body, or None."""
    g = re.search(r"if\s*\(W_tick\)\s*begin\b", code)
    if not g:
        return None
    depth, end = 1, len(code)
    for tok in re.finditer(r"\bbegin\b|\bend\b", code[g.end():]):
        depth += 1 if tok.group(0) == "begin" else -1
        if depth == 0:
            end = g.end() + tok.start()
            break
    return (g.end(), end)


def _siren_cfg(src):
    """alarm_siren.v's cadence datapath as numbers a scope would measure.

    cfg['error'] lists every shape that could not be found, so a rename fails the
    pass loudly instead of quietly simulating something else. 'per_sample' is the
    one fact no amount of arithmetic can tell you -- where the increment sits
    relative to the 48 kHz tick guard -- so it is read off the block structure.
    """
    code = _strip_comments(src)
    cfg, err = {}, []

    def grab(name, pattern, group=1, flags=0):
        m = re.search(pattern, code, flags)
        if not m:
            err.append("no %s (%s)" % (name, pattern[:34]))
            return None
        return m.group(group)

    cfg['CLK_FREQ_HZ'] = _v_num(grab('CLK_FREQ_HZ',
                                     r"parameter integer CLK_FREQ_HZ\s*=\s*([\d_]+)"))
    cfg['SAMPLE_RATE_HZ'] = _v_num(grab('SAMPLE_RATE_HZ',
                                        r"parameter integer SAMPLE_RATE_HZ\s*=\s*([\d_]+)"))
    cfg['steps'] = dict((n, _v_num(v)) for n, v in re.findall(
        r"localparam \[31:0\] (STEP_\w+)\s*=\s*(32'd[\d_]+)", code))
    alt = grab('W_alt', r"wire\s+W_alt\s*=\s*S_mod_cnt\[\s*(\d+)\s*\]")
    puls = grab('W_pulse', r"wire\s+W_pulse\s*=\s*S_mod_cnt\[\s*(\d+)\s*\]")
    cfg['alt_bit'] = int(alt) if alt else None
    cfg['pulse_bit'] = int(puls) if puls else None
    fire = re.search(r"TYPE_FIRE\)\s*\?\s*\(\s*W_alt\s*\?\s*(STEP_\w+)\s*:\s*"
                     r"(STEP_\w+)\s*\)", code)
    evac = re.search(r"TYPE_EVAC\)\s*\?\s*(STEP_\w+)", code)
    gen = re.search(r":\s*(STEP_\w+)\s*;", code)
    cfg['fire'] = fire.groups() if fire else None
    cfg['evac'] = evac.group(1) if evac else None
    cfg['general'] = gen.group(1) if gen else None
    if not (fire and evac and gen):
        err.append("W_step's three type arms did not all match")
    cfg['evac_gate'] = bool(re.search(
        r"W_audible\s*=\s*I_en\s*&&\s*\(\(I_type\s*==\s*TYPE_EVAC\)\s*\?\s*"
        r"~W_pulse\s*:\s*1'b1\)", code))
    if not cfg['evac_gate']:
        err.append("W_audible is no longer the EVAC-only gate")
    cfg['held_at_zero'] = bool(re.search(r"else\s+S_mod_cnt\s*<=\s*16'd0\s*;", code))
    adv = re.search(r"S_mod_cnt\s*<=\s*S_mod_cnt\s*\+", code)
    cfg['advance_stmt'] = bool(adv)
    span = _tick_guard_span(code)
    cfg['per_sample'] = bool(adv and span and span[0] <= adv.start() < span[1])
    cfg['error'] = err
    return cfg


def _hz(cfg, step_name):
    """Tone a 32-bit phase step really produces at the parsed sample rate."""
    step = cfg['steps'].get(step_name)
    if step is None or not cfg.get('SAMPLE_RATE_HZ'):
        return None
    return step * cfg['SAMPLE_RATE_HZ'] / float(1 << 32)


def _siren_shape(cfg, atype):
    """(list of (Hz, ms each), audible duty) for one type code, or None."""
    if cfg.get('error'):
        return None
    rate = cfg['SAMPLE_RATE_HZ'] if cfg['per_sample'] else cfg['CLK_FREQ_HZ']
    if not rate:
        return None
    half = lambda bit: (1 << bit) * 1000.0 / rate      # noqa: E731 (one-liner)
    if atype == TYPE_FIRE:
        lo, hi = cfg['fire']
        return [(_hz(cfg, lo), half(cfg['alt_bit'])),
                (_hz(cfg, hi), half(cfg['alt_bit']))], 1.0
    if atype == TYPE_EVAC:
        return [(_hz(cfg, cfg['evac']), half(cfg['pulse_bit']))], 0.5
    return [(_hz(cfg, cfg['general']), None)], 1.0


def _buzzer_cfg(src, inst_src):
    """buzzer_beep.v's constants, with top's instance overrides applied."""
    code = _strip_comments(src)
    cfg, err = {}, []

    def grab(name, pattern):
        m = re.search(pattern, code)
        if not m:
            err.append("no %s" % name)
            return None
        return m.group(1)

    def num(name, pattern):
        return _v_num(grab(name, pattern))

    for nm, pat in (('CLK_FREQ_HZ', r"parameter integer CLK_FREQ_HZ\s*=\s*([\d_]+)"),
                    ('TONE_HZ', r"parameter integer TONE_HZ\s*=\s*([\d_]+)"),
                    ('WINDOW_MS', r"parameter integer WINDOW_MS\s*=\s*([\d_]+)")):
        own = num(nm, pat)
        over = re.search(r"\.%s\s*\(\s*([\d_]+)\s*\)" % nm, inst_src)
        cfg[nm] = _v_num(over.group(1)) if over else own
        cfg[nm + '_overridden'] = bool(over)
    for nm, pat in (('ON_FIRE', r"ON_FIRE\s*=\s*([\w]+)\s*;"),
                    ('ON_EVAC', r"ON_EVAC\s*=\s*([\d_]+)\s*;"),
                    ('ON_GEN', r"ON_GEN\s*=\s*([\d_]+)\s*;")):
        raw = grab(nm, pat)
        cfg[nm] = cfg['WINDOW_MS'] if raw == 'WINDOW_MS' else _v_num(raw)
    cfg['HALF_TONE'] = (cfg['CLK_FREQ_HZ'] // cfg['TONE_HZ'] // 2
                        if cfg.get('CLK_FREQ_HZ') and cfg.get('TONE_HZ') else None)
    cfg['MS_TICKS'] = (cfg['CLK_FREQ_HZ'] // 1000) if cfg.get('CLK_FREQ_HZ') else None
    cfg['ladder_guard'] = grab('ladder guard',
                               r"if \((I_alarm && \(I_level != 2'd0\))\) begin")
    cfg['envelope_terms'] = bool(re.search(
        r"W_envelope\s*=\s*I_alarm && \(I_level != 2'd0\) && \(S_win_ms < W_on_ms\)",
        code))
    cfg['silence_driven'] = bool(re.search(r"S_tone_cnt <= 15'd0;\s*O_beep\s*<= 1'b0;",
                                           code, re.S))
    cfg['gated_by_enable'] = bool(re.search(r"end else if \(EMERGENCY_ENABLE\) begin",
                                            code))
    cfg['error'] = err
    return cfg


def _buzzer_walk(clk_hz, tone_hz, window_ms, on_ms, level=2, alarm=1,
                 ladder='armed', n_windows=3):
    """Cycle-accurate walk of buzzer_beep.v's three counters at shrunk constants.

    The tone divider, the ms prescaler and the window ladder are independent
    counters, so dividing all three rates by the same integer leaves the same
    arithmetic and turns a 30 M-edge soak of one 600 ms window into a few hundred.
    ladder='envelope' is the NEGATIVE CONTROL: the shape this file used to have,
    where running the ladder off the envelope instead of the arming level made the
    off-time unreachable.
    """
    half_tone = clk_hz // tone_hz // 2
    ms_ticks = clk_hz // 1000
    tone_cnt = ms_cnt = win = 0
    beep = 0
    envs, beeps = [], []
    for _ in range(int(window_ms * n_windows * ms_ticks)):
        armed = bool(alarm and level != 0)
        sounding = bool(armed and win < on_ms)
        if ladder == 'armed':
            run = armed
        else:
            run = sounding
            if not sounding:
                ms_cnt = win = 0
        if run:
            if ms_cnt >= ms_ticks - 1:
                ms_cnt = 0
                win = 0 if win >= window_ms - 1 else win + 1
            else:
                ms_cnt += 1
        if sounding:
            if tone_cnt >= half_tone - 1:
                tone_cnt = 0
                beep ^= 1
            else:
                tone_cnt += 1
        else:
            tone_cnt = 0
            beep = 0
        envs.append(1 if sounding else 0)
        beeps.append(beep)
    return envs, beeps


def _duty_and_gap(run, ms_ticks):
    """Sounding fraction and longest silence, in ms, over the trailing windows."""
    envs = run[0]
    tail = envs[len(envs) // 3:]
    duty = sum(tail) / float(len(tail))
    longest, cur = 0, 0
    for e in tail:
        cur = 0 if e else cur + 1
        longest = max(longest, cur)
    return duty, longest / float(ms_ticks)


def _measured_tone_hz(envs, beeps, clk_hz):
    """Frequency measured from the O_beep edges themselves, not from the divider.

    Mean edge interval, not edge count over a window: the trailing slice is not a
    whole number of periods, and counting edges across it was 4% high on a 100 Hz
    tone. The first interval is dropped because the slice can start mid-period.
    """
    lo = len(envs) // 3
    edges = [i for i in range(lo + 1, len(envs))
             if envs[i] and envs[i - 1] and beeps[i] != beeps[i - 1]]
    gaps = [b - a for a, b in zip(edges, edges[1:])][1:]
    if not gaps:
        return None
    return clk_hz / float(2 * (sum(gaps) / float(len(gaps))))


# ---------------------------------------------------------------------------
# Pass J -- what the two sound channels actually do differently per type
# ---------------------------------------------------------------------------
def pass_j(res, verbose):
    print("=" * 78)
    print("J. Per-type cadence: the HDMI siren and the on-board horn")
    print("=" * 78)

    cfg = _siren_cfg(SIREN_SRC)
    res.add(not cfg['error'], "alarm_siren.v's cadence datapath parses",
            cfg['error'] and "; ".join(cfg['error']) or
            "steps=%s alt bit%d pulse bit%d @ %d Hz from %d Hz"
            % (sorted(cfg['steps']), cfg['alt_bit'], cfg['pulse_bit'],
               cfg['SAMPLE_RATE_HZ'], cfg['CLK_FREQ_HZ']))

    res.add(bool(cfg.get('advance_stmt')) and bool(cfg.get('per_sample')),
            "the cadence counter advances once per SAMPLE, not per video clock",
            "increment inside the 48 kHz tick guard=%d; at 25 MHz mod_cnt[14] "
            "would toggle every 0.655 ms instead of every 341.3 ms"
            % (1 if cfg.get('per_sample') else 0))

    want_ms = ((1 << 14) * 1000.0 / 48_000.0, (1 << 13) * 1000.0 / 48_000.0)
    if not cfg['error']:
        fire = _siren_shape(cfg, TYPE_FIRE)
        evac = _siren_shape(cfg, TYPE_EVAC)
        gen = _siren_shape(cfg, TYPE_GENERAL)
        f_ms = fire[0][0][1]
        res.add(abs(f_ms - want_ms[0]) < 1.0 and
                all(abs(f - _hz(cfg, s)) < 1.0 for (f, _), s in zip(fire[0], cfg['fire'])),
                "fire = 800/1000 Hz two-tone, %.1f ms each" % want_ms[0],
                "measured %.1f Hz and %.1f Hz, each %.1f ms"
                % (fire[0][0][0], fire[0][1][0], f_ms))
        e_ms = evac[0][0][1]
        res.add(abs(e_ms - want_ms[1]) < 1.0 and evac[1] == 0.5,
                "evac = one tone pulsed %.1f ms on / %.1f ms off" % (want_ms[1],
                                                                     want_ms[1]),
                "tone %.1f Hz, window %.1f ms, audible duty %.3f"
                % (evac[0][0][0], e_ms, evac[1]))
        res.add(gen[1] == 1.0 and abs(gen[0][0][0] - 700.0) < 1.0,
                "general = one continuous tone at 700 Hz",
                "tone %.4f Hz duty %.3f" % (gen[0][0][0], gen[1]))
        sig = lambda t: tuple(sorted(round(f, 1) for f, _ in _siren_shape(cfg, t)[0])) \
            + (_siren_shape(cfg, t)[1],)                    # noqa: E731
        shapes = [sig(t) for t in (TYPE_FIRE, TYPE_EVAC, TYPE_GENERAL)]
        res.add(len(set(shapes)) == 3,
                "the three type codes really are three different sounds",
                "without this the whole differentiation claim could be vacuous: %s"
                % (shapes,))
        res.add(fire[1] == 1.0 and gen[1] == 1.0 and evac[1] == 0.5
                and all(100.0 <= ms <= 1000.0 for _, ms in fire[0]),
                "each alternation is slow enough for an ear to call it two tones",
                "alternation %.1f ms; a siren that swaps every sub-millisecond is "
                "a buzz, and the per-clock bug made exactly that" % f_ms)
        res.add(cfg['held_at_zero'] and _siren_shape(cfg, TYPE_EVAC)[0][0][1] > 0,
                "the pattern counter is held at 0 while the alarm is down",
                "so a takeover always starts on the loud half of its own window")
        # NEGATIVE CONTROL: the shipped-until-tonight form of the line. Hoisting
        # the increment out of the tick guard is not a hypothetical; it is what
        # the file said, and the pass above has to be able to see it.
        code = _strip_comments(SIREN_SRC)
        adv = re.search(r"[ ]*if \(I_en\) S_mod_cnt <= S_mod_cnt \+ 16'd1;\n"
                        r"[ ]*else +S_mod_cnt <= 16'd0;\n", code)
        hoist_end = re.search(r"end else begin\n[ ]*S_tick_acc <= W_tick_next;\n[ ]*end\n",
                              code)
        if adv and hoist_end:
            mutated = (code[:adv.start()] + code[adv.end():hoist_end.end()]
                       + adv.group(0) + code[hoist_end.end():])
            bad = _siren_cfg(mutated)
            slow = _siren_shape(bad, TYPE_EVAC)[0][0][1]
            mod_hz = 1000.0 / (2 * slow)
            res.add(not bad['per_sample'] and abs(slow - want_ms[1] / 520.833) < 1.0,
                    "NEGATIVE CONTROL: the per-clock cadence is caught",
                    "placement read as per-clock=%d, evac window collapses to "
                    "%.3f ms = a %.0f Hz amplitude modulation, not a pulsed blast"
                    % (0 if bad['per_sample'] else 1, slow, mod_hz))
        else:
            res.add(False, "NEGATIVE CONTROL: the per-clock cadence is caught",
                    "mutation did not apply (%d/%d anchors), so this proved nothing"
                    % (1 if adv else 0, 1 if hoist_end else 0))

    # ---- the horn. Same claim, second channel, second arithmetic.
    bparam = _param_src(TOP_SRC, 'buzzer_beep', 'u_buzzer_beep')
    b = _buzzer_cfg(BUZZ_SRC, bparam)
    res.add(not b['error'], "buzzer_beep.v's constants parse, with top's overrides",
            "; ".join(b['error']) or
            "CLK=%d TONE=%d%s WINDOW=%d ms ON fire/evac/gen=%d/%d/%d"
            % (b['CLK_FREQ_HZ'], b['TONE_HZ'],
               " (overridden)" if b['TONE_HZ_overridden'] else "",
               b['WINDOW_MS'], b['ON_FIRE'], b['ON_EVAC'], b['ON_GEN']))
    if b['error']:
        return

    shipped = b['CLK_FREQ_HZ'] / float(2 * b['HALF_TONE'])
    res.add(abs(shipped - b['TONE_HZ']) < 1.0
            and b['CLK_FREQ_HZ'] % (2 * b['HALF_TONE']) == 0,
            "the horn's divider is exact at the shipped constants",
            "%d Hz / (2 x %d) = %.4f Hz, 50%% duty by construction"
            % (b['CLK_FREQ_HZ'], b['HALF_TONE'], shipped))

    # Shrink every rate by the same factor so the walk stays cycle-accurate.
    k = 50
    small_clk, small_tone = b['CLK_FREQ_HZ'] // k // 100, b['TONE_HZ'] // 10
    small_win = b['WINDOW_MS'] // k
    on_ms = {TYPE_FIRE: b['ON_FIRE'] // k, TYPE_EVAC: b['ON_EVAC'] // k,
             TYPE_GENERAL: b['ON_GEN'] // k}
    res.add(small_clk % (2 * (small_clk // small_tone // 2)) == 0 and
            all(b[w] % k == 0 for w in ('WINDOW_MS', 'ON_FIRE', 'ON_EVAC', 'ON_GEN')),
            "the shrunk walk divides exactly, so it is the same arithmetic",
            "clk %d Hz tone %d Hz window %d ms on %s"
            % (small_clk, small_tone, small_win, sorted(on_ms.values())))

    runs = {}
    for t in (TYPE_FIRE, TYPE_EVAC, TYPE_GENERAL):
        runs[t] = _buzzer_walk(small_clk, small_tone, small_win, on_ms[t],
                               n_windows=6)
    ms = small_clk // 1000
    duties = dict((t, _duty_and_gap(runs[t], ms)[0]) for t in runs)
    want_duty = dict((t, on_ms[t] / float(small_win)) for t in on_ms)
    res.add(all(abs(duties[t] - want_duty[t]) < 0.01 for t in duties),
            "each type's sounding fraction is its ON_ms over the window",
            "measured %s want %s"
            % (dict((t, round(v, 3)) for t, v in duties.items()),
               dict((t, round(v, 3)) for t, v in want_duty.items())))
    res.add(len(set(round(v, 3) for v in duties.values())) == 3,
            "three type codes, three horn patterns -- all distinct",
            "duty %s; two identical ones would be one alarm you cannot name blind"
            % (dict((t, round(v, 3)) for t, v in duties.items()),))
    meas = _measured_tone_hz(*runs[TYPE_FIRE], small_clk)
    res.add(meas is not None and abs(meas - small_tone) < 1.0,
            "the tone frequency is measured from O_beep's edges, not from the parameter",
            "%d Hz walked, %d Hz asked for" % (round(meas or 0, 3), small_tone))
    fire_gap = _duty_and_gap(runs[TYPE_FIRE], ms)[1]
    evac_gap = _duty_and_gap(runs[TYPE_EVAC], ms)[1]
    res.add(fire_gap == 0.0 and 1.0 < evac_gap <= (small_win - on_ms[TYPE_EVAC]) + 1,
            "fire is continuous because ON_FIRE == WINDOW_MS, not by a special case",
            "longest silence fire/evac = %.1f/%.1f ms; the comparator can never be "
            "satisfied for fire, so the long blast needs no extra case arm"
            % (fire_gap, evac_gap))
    mute = _buzzer_walk(small_clk, small_tone, small_win, on_ms[TYPE_EVAC], level=0)
    res.add(not any(mute[0]) and not any(mute[1]),
            "VOLM 0 silences the horn, and silence is a driven 0",
            "%d sounding edges, %d beep edges out of %d"
            % (sum(mute[0]), sum(mute[1]), len(mute[0])))

    res.add(b['ladder_guard'] == 'I_alarm && (I_level != 2\'d0)'
            and b['envelope_terms'],
            "the window ladder is armed by the alarm level, never by the envelope",
            "guard reads `%s`, envelope keeps the win_ms compare" % b['ladder_guard'])
    bad = _buzzer_walk(small_clk, small_tone, small_win, on_ms[TYPE_EVAC],
                       ladder='envelope', n_windows=6)
    bad_duty, bad_gap = _duty_and_gap(bad, ms)
    res.add(bad_duty > 0.9 and bad_gap <= 1.0
            and bad_duty - duties[TYPE_EVAC] > 0.5,
            "NEGATIVE CONTROL: envelope-gating the ladder makes every type continuous",
            "evac duty %.3f/%.1f ms silence walked right, %.3f/%.1f ms gated by the "
            "envelope -- the off-period becomes unreachable, the bug this file "
            "already had once" % (duties[TYPE_EVAC],
                                  _duty_and_gap(runs[TYPE_EVAC], ms)[1],
                                  bad_duty, bad_gap))
    threaded = bool(re.search(r"\.EMERGENCY_ENABLE\s*\(\s*EMERGENCY_ENABLE\s*\)",
                              bparam))
    res.add(b['silence_driven'] and b['gated_by_enable']
            and bool(re.search(r"O_beep\s*<=\s*1'b0", _strip_comments(BUZZ_SRC)))
            and threaded,
            "at EMERGENCY_ENABLE=0 the horn has no loads and the pin stays 0",
            "silence-driven=%d enable-gated=%d parameter threaded into the instance=%d"
            % (b['silence_driven'], b['gated_by_enable'], 1 if threaded else 0))


# ---------------------------------------------------------------------------
# Pass K -- the burn-in sequencer, i.e. the 7x24 claim
# ---------------------------------------------------------------------------
def pass_k(res, verbose):
    print("=" * 78)
    print("K. Burn-in sequencer: self-cycling soak, inert in the shipped build")
    print("=" * 78)

    # burn_sec is an integer parameter, so shrink the clock the same way the
    # debouncer does instead of walking 50 M edges per phase.
    per_phase = 1 * 1000 * 5                       # BURN_SEC=1 at 5 ticks/ms
    s = System(burn_sec=1, ticks_per_ms=5)
    phases = []
    s.settle(per_phase // 2 - 2)
    for _ in range(7):
        s.settle(per_phase)
        phases.append((s.st['burn_on'], s.st['req_cmd'], s.st['emg_state']))
    ups = [p for p in phases if p[0]]
    res.add(len(ups) >= 3 and all(p[2] >> 2 for p in ups)
            and all(p[2] == 0 for p in phases if not p[0]),
            "the sequencer takes the panel over and lets go, unattended",
            "7 phases seen: %s" % (phases,))
    types_seen = sorted(set(p[1] for p in ups))
    cycle = [p[1] for p in phases if p[0]]
    res.add(types_seen == [TYPE_FIRE, TYPE_EVAC, TYPE_GENERAL]
            and len(set(cycle)) == 3,
            "every phase walks 1 -> 2 -> 3 -> 1, so a soak visits all three",
            "on-phases requested %s" % (cycle,))
    res.add(all(phases[i][0] != phases[i + 1][0] for i in range(len(phases) - 1)),
            "no ON phase is ever followed by another ON (50% duty, forever)",
            "a stuck sequencer would soak one state and call it 7x24: %s"
            % ([p[0] for p in phases],))

    # Inert in the build anyone is actually going to flash.
    q = System(ticks_per_ms=5)
    q.settle(3 * per_phase)
    res.add(q.burn_sec == 0 and q.st['burn_cnt'] == 0 and q.st['burn_on'] == 0
            and q.st['emg_state'] == 0 and q.st['req_cmd'] == 0,
            "at the shipped BURN_SEC=0 the timer never moves and never self-triggers",
            "burn_cnt=%d burn_on=%d state=%d -- an unrequested alarm on a signage "
            "board is the worst possible bug this feature could have"
            % (q.st['burn_cnt'], q.st['burn_on'], q.st['emg_state']))
    cparam = _param_src(TOP_SRC, 'emergency_ctrl', 'u_emergency_ctrl')
    res.add(bool(re.search(r"\.BURN_SEC\s*\(\s*0\s*\)", cparam)),
            "top ships .BURN_SEC(0), so the sequencer is pruned at synthesis",
            "parameter block is %d chars; the soak generator is a build-time switch"
            % len(cparam))

    # The operator outranks the test generator in the very same cycle.
    r = System(burn_sec=1, ticks_per_ms=5)
    r.settle(40)
    r.st['burn_req_v'] = 1
    r.st['burn_req'] = TYPE_EVAC
    r.st['cmd_emg_set'] = 1
    r.st['cmd_emg'] = TYPE_GENERAL
    r.settle(1)
    res.add(r.st['req_cmd'] == TYPE_GENERAL and r.st['burn_req_v'] == 0,
            "a command and a burn publish in one cycle: the command wins",
            "req_cmd=%d (asked %d, offered %d) and the publish was consumed"
            % (r.st['req_cmd'], TYPE_GENERAL, TYPE_EVAC))

    # A closed contact is not the sequencer's to release.
    h = System(burn_sec=1, ticks_per_ms=5)
    h.pin_aut = 0
    h.settle(40)                                   # let T2 arm and dominate
    off_phases = 0
    stayed = 0
    for _ in range(6):
        h.settle(per_phase)
        if h.st['burn_on'] == 0:
            off_phases += 1
            stayed += 1 if (h.st['emg_state'] >> 2) and \
                (h.st['emg_state'] & 3) == AUTO_TYPE else 0
    res.add(off_phases >= 2 and stayed == off_phases,
            "the sequencer's ALRM 0 cannot release a held hardwire contact",
            "%d off-phases, %d kept the fire alarm up; release is an AND over the "
            "requestors, so a shorted line soaks as a persistent alarm"
            % (off_phases, stayed))
    h.pin_aut = 1
    h.settle(2 * per_phase)
    res.add(h.st['emg_state'] == 0 or (h.st['emg_state'] & 3) != 0,
            "after the contact opens the sequencer is back in charge",
            "state=%d -- nothing latched to the contact's type" % h.st['emg_state'])

    # Model/RTL alignment. The model mirrors two always blocks; if the RTL's
    # sequencer ever starts naming the command input, the mirror is a lie and
    # every check above silently changes meaning.
    ccode = _strip_comments(CTRL_SRC)
    seq = re.search(r"else if \((EMERGENCY_ENABLE && BURN_SEC != 0)\)", ccode)
    load = re.search(r"if \(EMERGENCY_ENABLE && \(I_cmd_emg_set \|\| "
                     r"(\w+)\)\)\s*\n\s*req_cmd <= I_cmd_emg_set \? I_cmd_emg : "
                     r"(\w+);", ccode)
    res.add(bool(seq) and bool(load) and load.group(1) == 'burn_req_v'
            and load.group(2) == 'burn_req',
            "the RTL still splits publish and load the way the model mirrors it",
            "sequencer guard names no command input=%d; the load is a mux with the "
            "operator first=%d" % (bool(seq), bool(load)))
    res.add(bool(re.search(r"burn_req_v <= 1'b0;", ccode))
            and len(re.findall(r"burn_req_v <= 1'b1;", ccode)) == 2,
            "the publish is a one-cycle flag, cleared every edge and set on both steps",
            "the model's req_cmd therefore lags the on/off edge by one clk, which is "
            "why K asserts phases, not exact edges")

    # NEGATIVE CONTROL: drop the release publish and the soak tests one state.
    z = System(burn_sec=1, ticks_per_ms=5, burn_stuck=1)
    z.settle(4 * per_phase)
    res.add((z.st['emg_state'] >> 2) == 1 and z.st['burn_on'] == 0,
            "NEGATIVE CONTROL: a sequencer that never releases is caught",
            "stuck model still has %d on the panel after the timer turned off, so "
            "the 50%% duty check above has an edge" % (z.st['emg_state'],))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--verbose", action="store_true")
    args = ap.parse_args()
    res = Result()
    pass_a(res, args.verbose)
    pass_b(res, args.verbose)
    pass_c(res, args.verbose)
    pass_d(res, args.verbose)
    pass_e(res, args.verbose)
    pass_f(res, args.verbose)
    pass_g(res, args.verbose)
    pass_h(res, args.verbose)
    pass_i(res, args.verbose)
    pass_j(res, args.verbose)
    pass_k(res, args.verbose)
    print("=" * 78)
    total = len(res.rows)
    print("%d/%d checks passed, %d failed" % (total - res.failed, total,
                                              res.failed))
    print("=" * 78)
    sys.exit(1 if res.failed else 0)


if __name__ == "__main__":
    main()
