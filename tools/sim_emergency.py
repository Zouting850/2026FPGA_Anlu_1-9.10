    ms = (span or 0) * CLK_PERIOD / 1e6
    res.add(span is not None and abs(span - want) <= 2,
            "release window is 20.00 ms, not 2 ms and not 200 ms",
            "%d clk edges = %.3f ms (want %d = %d x %d ms + 3 sync)"
            % (span, ms, want, s.cnt_max // TICKS_PER_MS_REAL, 1))
    res.add(19.9 < ms < 20.2,
            "release debounce matches the 20 ms the keys already use",
            "key_press_debounce is DEBOUNCE_MS=20; this measures %.3f ms" % ms)


